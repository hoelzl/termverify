#!/usr/bin/env python3
"""Generate the documentation indexes from each page's frontmatter.

Usage:
    uv --no-config run python scripts/build_doc_indexes.py           # write
    uv --no-config run python scripts/build_doc_indexes.py --check   # gate

Each ``index.md`` this script writes is a derived view (issue #322): it is
regenerated from the ``summary`` (and, for agent records, ``type``,
``status``, and ``date``) frontmatter of the pages it lists, so it can never
miss a page or disagree with one. Never edit a generated index by hand; edit
the page's frontmatter and rerun this script. ``--check`` fails, without
writing, when any generated index differs from what the script would write —
the pre-commit hook and the CI documentation job run it that way.

Agent-record frontmatter is validated by ``scripts/validate_agent_docs.py``;
this script only reads it.
"""

from __future__ import annotations

import argparse
import datetime
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

import yaml

COMMAND = "uv --no-config run python scripts/build_doc_indexes.py"
HEADER = (
    f"<!-- GENERATED by `{COMMAND}` from the frontmatter of the pages listed"
    " below. Do not edit: change a page's frontmatter and regenerate. -->\n"
)
EXEMPT_FILENAMES = frozenset({"README.md", "index.md"})


@dataclass(frozen=True)
class Page:
    """One listed page: its path relative to the index and its metadata."""

    link: str
    title: str
    meta: Mapping[str, object]

    def field(self, name: str) -> str:
        value = self.meta.get(name, "")
        if isinstance(value, datetime.date):
            return value.isoformat()
        return str(value)


@dataclass(frozen=True)
class IndexSpec:
    """How to render one generated index."""

    directory: str
    title: str
    intro: str
    render: Callable[[Sequence[Page]], str]
    recursive: bool = False


def _frontmatter(text: str) -> dict[str, object]:
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---\n", 4)
    if end == -1:
        return {}
    try:
        data = yaml.safe_load(text[4:end])
    except yaml.YAMLError:
        return {}
    return data if isinstance(data, dict) else {}


def _title(text: str, fallback: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def collect_pages(directory: Path, *, recursive: bool) -> list[Page]:
    """Return the listable pages in *directory*, sorted by link."""
    paths = directory.rglob("*.md") if recursive else directory.glob("*.md")
    pages: list[Page] = []
    for path in sorted(paths):
        if path.name in EXEMPT_FILENAMES:
            continue
        text = path.read_text(encoding="utf-8")
        link = path.relative_to(directory).as_posix()
        pages.append(Page(link, _title(text, path.stem), _frontmatter(text)))
    return pages


def _record_table(pages: Sequence[Page]) -> str:
    rows = sorted(pages, key=lambda page: (page.field("date"), page.link), reverse=True)
    lines = ["| Record | Status | Date | Summary |", "| --- | --- | --- | --- |"]
    lines.extend(
        f"| [{_cell(page.title)}]({page.link}) | {page.field('status')}"
        f" | {page.field('date')} | {_cell(page.field('summary'))} |"
        for page in rows
    )
    return "\n".join(lines) + "\n"


def render_records(pages: Sequence[Page]) -> str:
    return _record_table(pages)


def render_by_type(pages: Sequence[Page]) -> str:
    sections = (
        ("Decisions", "decision"),
        ("Assessments", "assessment"),
        ("Reviews filed before `reviews/` existed", "review"),
    )
    parts: list[str] = []
    for heading, record_type in sections:
        group = [page for page in pages if page.field("type") == record_type]
        if group:
            parts.append(f"## {heading}\n\n{_record_table(group)}")
    return "\n".join(parts)


def render_handovers(pages: Sequence[Page]) -> str:
    current = [page for page in pages if not page.link.startswith("archive/")]
    archived = [page for page in pages if page.link.startswith("archive/")]
    parts = []
    for heading, group in (("Current", current), ("Archive", archived)):
        body = _record_table(group) if group else "None.\n"
        parts.append(f"## {heading}\n\n{body}")
    return "\n".join(parts)


def render_guides(pages: Sequence[Page]) -> str:
    rows = sorted(pages, key=lambda page: page.title.lower())
    return "".join(
        f"- [{page.title}]({page.link}) — {page.field('summary')}\n" for page in rows
    )


INDEXES: tuple[IndexSpec, ...] = (
    IndexSpec(
        "docs/agent/design",
        "Design Records",
        "Architecture decision records, assessments, and early review reports."
        " Conventions: [`docs/README.md`](../../README.md).",
        render_by_type,
    ),
    IndexSpec(
        "docs/agent/reviews",
        "Review Reports",
        "Conventions: [`README.md`](README.md).",
        render_records,
    ),
    IndexSpec(
        "docs/agent/plans",
        "Implementation Plans",
        "Conventions: [`README.md`](README.md).",
        render_records,
    ),
    IndexSpec(
        "docs/agent/prompts",
        "Worktree Agent Prompts",
        "Conventions: [`README.md`](README.md). Only `current` prompts may be run.",
        render_records,
    ),
    IndexSpec(
        "docs/agent/handovers",
        "Handover Index",
        "Lifecycle and authoring rules:"
        " [`agent-workflow.md`](../../developer-guide/agent-workflow.md)."
        " GitHub issues, pull requests, and Git remain the source of truth for"
        " volatile work state.",
        render_handovers,
        recursive=True,
    ),
    IndexSpec(
        "docs/developer-guide",
        "Developer Guide",
        "Workflows and operating guides for contributors and agents. Concepts"
        " live in the [knowledge bundle](../knowledge/index.md).",
        render_guides,
    ),
)


def render_index(root: Path, spec: IndexSpec) -> str:
    """Return the full text of the generated index for *spec*."""
    pages = collect_pages(root / spec.directory, recursive=spec.recursive)
    return f"{HEADER}\n# {spec.title}\n\n{spec.intro}\n\n{spec.render(pages)}"


def missing_summaries(root: Path) -> list[str]:
    """Return listed pages whose frontmatter has no ``summary``."""
    errors: list[str] = []
    for spec in INDEXES:
        directory = root / spec.directory
        errors.extend(
            f"{spec.directory}/{page.link}: missing frontmatter summary"
            for page in collect_pages(directory, recursive=spec.recursive)
            if not page.field("summary")
        )
    return errors


def build(root: Path, *, check: bool) -> list[str]:
    """Write (or, with *check*, verify) every index; return problems."""
    problems = missing_summaries(root)
    for spec in INDEXES:
        target = root / spec.directory / "index.md"
        expected = render_index(root, spec)
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == expected:
            continue
        if check:
            problems.append(
                f"{spec.directory}/index.md is stale — run `{COMMAND}` and"
                " commit the result"
            )
        else:
            target.write_text(expected, encoding="utf-8", newline="\n")
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate documentation indexes.")
    parser.add_argument(
        "--check", action="store_true", help="fail on stale indexes, write nothing"
    )
    args = parser.parse_args(argv)
    problems = build(Path(), check=args.check)
    if problems:
        print("\n".join(problems))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
