"""Documentation indexes are derived views generated from page frontmatter.

Issue #322: only two of the agent-record folders had an index, and those
were hand-maintained. ``scripts/build_doc_indexes.py`` regenerates every
index from the pages' own metadata, and ``--check`` gates staleness.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest


def load_builder() -> ModuleType:
    path = Path("scripts/build_doc_indexes.py")
    spec = importlib.util.spec_from_file_location("doc_index_builder", path)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    # Dataclasses resolve their module through sys.modules at class creation.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _page(root: Path, relative: str, front: str, title: str = "Title") -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"---\n{front}---\n\n# {title}\n", encoding="utf-8")


def _tree(root: Path) -> None:
    record = "status: {status}\ndate: {date}\nsummary: {summary}\ntype: {type}\n"
    _page(
        root,
        "docs/agent/design/adr.md",
        record.format(
            status="accepted",
            date="2026-07-19",
            summary="Decides | X.",
            type="decision",
        ),
        title="An ADR",
    )
    _page(
        root,
        "docs/agent/design/look.md",
        record.format(
            status="current",
            date="2026-07-14",
            summary="Assesses Y.",
            type="assessment",
        ),
    )
    for folder, record_type, status in (
        ("reviews", "review", "resolved"),
        ("plans", "plan", "active"),
        ("prompts", "prompt", "retired"),
        ("handovers", "handover", "active"),
        ("handovers/archive", "handover", "complete"),
    ):
        _page(
            root,
            f"docs/agent/{folder}/one.md",
            record.format(
                status=status, date="2026-08-01", summary="Says Z.", type=record_type
            ),
        )
    _page(root, "docs/developer-guide/guide.md", "summary: How to do it.\n", "Guide")
    (root / "docs/agent/reviews/README.md").write_text("# Conventions\n", "utf-8")


def test_build_writes_every_index_with_a_generated_header(tmp_path: Path) -> None:
    _tree(tmp_path)
    builder = load_builder()

    assert builder.build(tmp_path, check=False) == []

    for spec in builder.INDEXES:
        text = (tmp_path / spec.directory / "index.md").read_text(encoding="utf-8")
        assert text.startswith("<!-- GENERATED by `uv --no-config run python")
    design = (tmp_path / "docs/agent/design/index.md").read_text(encoding="utf-8")
    assert "[An ADR](adr.md) | accepted | 2026-07-19 | Decides \\| X." in design
    assert "## Assessments" in design and "## Reviews" not in design
    reviews = (tmp_path / "docs/agent/reviews/index.md").read_text(encoding="utf-8")
    assert "README.md)" in reviews and "(README.md) |" not in reviews
    handovers = (tmp_path / "docs/agent/handovers/index.md").read_text("utf-8")
    assert "(one.md)" in handovers and "(archive/one.md)" in handovers
    guide = (tmp_path / "docs/developer-guide/index.md").read_text(encoding="utf-8")
    assert "- [Guide](guide.md) — How to do it." in guide


def test_check_passes_on_fresh_indexes_and_writes_nothing(tmp_path: Path) -> None:
    _tree(tmp_path)
    builder = load_builder()
    builder.build(tmp_path, check=False)
    before = {p: p.read_bytes() for p in tmp_path.rglob("index.md")}

    assert builder.build(tmp_path, check=True) == []
    assert {p: p.read_bytes() for p in tmp_path.rglob("index.md")} == before


def test_check_reports_a_stale_index_without_rewriting_it(tmp_path: Path) -> None:
    _tree(tmp_path)
    builder = load_builder()
    builder.build(tmp_path, check=False)
    _page(
        tmp_path,
        "docs/agent/plans/two.md",
        "type: plan\nstatus: active\ndate: 2026-09-01\nsummary: New.\n",
    )
    stale = (tmp_path / "docs/agent/plans/index.md").read_text(encoding="utf-8")

    problems = builder.build(tmp_path, check=True)

    assert problems == [
        "docs/agent/plans/index.md is stale — run"
        " `uv --no-config run python scripts/build_doc_indexes.py` and commit"
        " the result"
    ]
    assert (tmp_path / "docs/agent/plans/index.md").read_text("utf-8") == stale


def test_missing_index_is_stale_under_check(tmp_path: Path) -> None:
    _tree(tmp_path)
    builder = load_builder()

    problems = builder.build(tmp_path, check=True)

    assert len(problems) == len(builder.INDEXES)


def test_pages_without_summary_are_reported(tmp_path: Path) -> None:
    _tree(tmp_path)
    (tmp_path / "docs/developer-guide/bare.md").write_text("# Bare\n", "utf-8")
    builder = load_builder()

    problems = builder.build(tmp_path, check=False)

    assert problems == ["docs/developer-guide/bare.md: missing frontmatter summary"]


def test_records_are_listed_newest_first(tmp_path: Path) -> None:
    _tree(tmp_path)
    _page(
        tmp_path,
        "docs/agent/plans/old.md",
        "type: plan\nstatus: completed\ndate: 2026-07-01\nsummary: Old.\n",
        title="Old plan",
    )
    builder = load_builder()
    builder.build(tmp_path, check=False)

    plans = (tmp_path / "docs/agent/plans/index.md").read_text(encoding="utf-8")

    assert plans.index("(one.md)") < plans.index("(old.md)")


def test_empty_handover_sections_say_none(tmp_path: Path) -> None:
    (tmp_path / "docs/agent/handovers").mkdir(parents=True)
    builder = load_builder()
    spec = next(s for s in builder.INDEXES if s.directory == "docs/agent/handovers")

    text = builder.render_index(tmp_path, spec)

    assert text.count("None.") == 2


def test_unparsable_frontmatter_is_treated_as_missing(tmp_path: Path) -> None:
    builder = load_builder()

    assert builder._frontmatter("# No frontmatter\n") == {}
    assert builder._frontmatter("---\nunterminated: yes\n") == {}
    assert builder._frontmatter("---\n- a list\n---\n") == {}
    assert builder._frontmatter("---\nkey: a: b\n---\n") == {}
    assert builder._title("no heading", "fallback") == "fallback"


def test_the_committed_indexes_are_current() -> None:
    builder = load_builder()

    assert builder.build(Path(), check=True) == []


def test_main_check_reports_stale_indexes(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    _tree(tmp_path)
    builder = load_builder()
    monkeypatch.chdir(tmp_path)

    assert builder.main(["--check"]) == 1
    assert "stale" in capsys.readouterr().out
    assert builder.main([]) == 0
    assert builder.main(["--check"]) == 0


def test_subfolders_are_indexed_and_archives_grouped(tmp_path: Path) -> None:
    _tree(tmp_path)
    _page(
        tmp_path,
        "docs/agent/plans/archive/done.md",
        "type: plan\nstatus: completed\ndate: 2026-07-01\nsummary: Done.\n",
    )
    builder = load_builder()
    builder.build(tmp_path, check=False)

    plans = (tmp_path / "docs/agent/plans/index.md").read_text(encoding="utf-8")

    assert "## Archive" in plans
    assert (
        plans.index("(one.md)")
        < plans.index("## Archive")
        < plans.index("(archive/done.md)")
    )


def test_successor_and_issue_are_linked(tmp_path: Path) -> None:
    _tree(tmp_path)
    _page(
        tmp_path,
        "docs/agent/handovers/archive/old.md",
        "type: handover\nstatus: superseded\ndate: 2026-07-01\nsummary: Old.\n"
        "issue: 87\nsuperseded_by: docs/agent/handovers/one.md\n",
    )
    builder = load_builder()
    builder.build(tmp_path, check=False)

    text = (tmp_path / "docs/agent/handovers/index.md").read_text(encoding="utf-8")

    assert "superseded → [successor](one.md)" in text
    assert "Old. ([#87](https://github.com/hoelzl/termverify/issues/87))" in text


def test_title_ignores_frontmatter_comments_and_code_fences() -> None:
    builder = load_builder()
    text = "---\nsummary: x\n# owner note\n---\n\n```bash\n# comment\n```\n\n# Real\n"

    assert builder._title(text, "fallback") == "Real"


def test_invalid_dates_do_not_crash_the_generator() -> None:
    builder = load_builder()

    assert builder._frontmatter("---\ndate: 2026-13-45\n---\n") == {}


def test_guides_sort_without_a_leading_article(tmp_path: Path) -> None:
    _tree(tmp_path)
    _page(tmp_path, "docs/developer-guide/z.md", "summary: Z.\n", "The Alpha Guide")
    builder = load_builder()
    builder.build(tmp_path, check=False)

    text = (tmp_path / "docs/developer-guide/index.md").read_text(encoding="utf-8")

    assert text.index("The Alpha Guide") < text.index("[Guide]")
